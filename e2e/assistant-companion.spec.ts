import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { expect, test } from './fixtures';

test.use({ storageState: process.env.E2E_STORAGE_STATE_PATH });
const chat = (page: import('@playwright/test').Page) => page.getByRole('dialog', { name: 'Smart Resume AI Assistant', exact: true });
const pet = (page: import('@playwright/test').Page) => page.locator('[data-assistant-mode="collapsed"] [data-companion-state]');
async function ready(page: import('@playwright/test').Page) {
  await page.addInitScript(() => localStorage.setItem('sra_nimbus_greeting_shown', '1'));
  await page.goto('/dashboard', { waitUntil: 'domcontentloaded' });
  const button = page.getByRole('button', { name: /open ai assistant/i });
  await expect(button).toBeVisible();
  await expect(button.locator('canvas')).toHaveAttribute('data-pixel-ready', '1');
  await expect(pet(page)).toHaveAttribute('data-active', '1');
  await expect(page.locator('[data-assistant-mode="collapsed"]')).toHaveAttribute('data-placement-ready', 'true');
  return button;
}

test('full-body rig moves, turns with actual dragging, settles, and keeps the next click', async ({ page, diagnostics }, info) => {
  const button = await ready(page);
  const joints = pet(page).locator('[data-rig]');
  await expect(pet(page).locator('[data-robot="cloud-head"]')).toHaveCount(1);
  await expect(pet(page).locator('[data-robot="screen"]')).toHaveCount(1);
  await expect(pet(page).locator('[data-robot="chevron"]')).toHaveCount(1);
  await expect(pet(page).locator('[data-robot="chest-terminal"]')).toHaveCount(1);
  const proportions = await pet(page).evaluate((element) => {
    const head = element.querySelector('[data-robot="cloud-head"]')!.getBoundingClientRect();
    const torso = element.querySelector('[data-robot="torso"]')!.getBoundingClientRect();
    return { width: head.width / torso.width, height: head.height / torso.height };
  });
  expect(proportions.width).toBeGreaterThan(2);
  expect(proportions.width).toBeLessThan(2.6);
  expect(proportions.height).toBeGreaterThan(2.8);
  expect(await joints.count()).toBeGreaterThanOrEqual(18);
  await expect(pet(page).locator('[data-rig="leftElbow"]')).toHaveCount(1);
  await expect(pet(page).locator('[data-rig="rightElbow"]')).toHaveCount(1);
  await expect(pet(page).locator('[data-rig="leftFoot"]')).toHaveCount(1);
  await expect(pet(page).locator('[data-rig="rightFoot"]')).toHaveCount(1);
  const head = pet(page).locator('[data-rig="head"]');
  const before = await head.getAttribute('transform');
  await expect.poll(() => head.getAttribute('transform')).not.toBe(before);
  const box = (await button.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x - 80, box.y - 90, { steps: 12 });
  await expect(pet(page)).toHaveAttribute('data-direction', 'left');
  const leftHip = await pet(page).locator('[data-rig="leftHip"]').getAttribute('transform');
  await page.mouse.move(box.x - 115, box.y - 100, { steps: 8 });
  await expect.poll(() => pet(page).locator('[data-rig="leftHip"]').getAttribute('transform')).not.toBe(leftHip);
  await page.mouse.move(box.x - 65, box.y - 110, { steps: 10 });
  await expect(pet(page)).toHaveAttribute('data-direction', 'right');
  await expect.poll(() => pet(page).getAttribute('data-motion')).not.toBe('walking'); // Held still stops the gait.
  await page.mouse.up();
  await expect(chat(page)).toHaveCount(0);
  const settled = (await button.boundingBox())!;
  expect(settled.x).toBeGreaterThanOrEqual(16);
  expect(settled.y).toBeGreaterThanOrEqual(16);
  expect(settled.x + settled.width).toBeLessThanOrEqual(page.viewportSize()!.width - 15);
  expect(settled.y + settled.height).toBeLessThanOrEqual(page.viewportSize()!.height - 15);
  const folder = path.join(process.cwd(), 'scripts/visual-qa/mascot/pixel-companion', info.project.name);
  await mkdir(folder, { recursive: true });
  await button.screenshot({ path: path.join(folder, 'original-companion.png'), animations: 'allow', caret: 'initial' });
  await page.screenshot({ path: path.join(folder, 'launcher.png'), animations: 'allow', caret: 'initial' });
  await button.click();
  await expect(chat(page)).toBeVisible();
  await chat(page).getByRole('button', { name: 'Collapse assistant', exact: true }).click();
  await expect(button).toBeVisible();
  await button.focus(); await button.press('Enter');
  await expect(chat(page)).toBeVisible();
  expect(diagnostics.consoleErrors).toEqual([]);
});

test('minimized pending request, accepted reply, error and genuine copy drive the companion', async ({ page, context, diagnostics }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  let release: (() => void) | undefined;
  let gate = new Promise<void>((resolve) => { release = resolve; });
  let fail = false;
  const requests: Array<{ message: string; history: unknown[]; context: unknown }> = [];
  await page.route('**/api/chat', async (route) => {
    requests.push(route.request().postDataJSON());
    await gate;
    await route.fulfill(fail ? { status: 502, json: { message: 'Companion lifecycle test failure' } } : { json: { reply: 'Keep your resume facts accurate.', provider: 'Isolated browser test' } });
  });
  const button = await ready(page); await button.click();
  const input = chat(page).getByRole('textbox');
  await input.fill('Review my resume facts.'); await input.press('Enter');
  await expect(chat(page)).toHaveAttribute('data-assistant-state', 'thinking');
  await chat(page).getByRole('button', { name: 'Collapse assistant', exact: true }).click();
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'thinking');
  const pendingHead = await pet(page).locator('[data-rig="head"]').getAttribute('transform');
  await expect.poll(() => pet(page).locator('[data-rig="head"]').getAttribute('transform')).not.toBe(pendingHead);
  release!();
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'answering');
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'idle');
  await button.click();
  await expect(chat(page).getByText('Keep your resume facts accurate.', { exact: true })).toBeVisible();
  await chat(page).getByRole('button', { name: 'Copy assistant answer', exact: true }).last().click();
  await expect(chat(page)).toHaveAttribute('data-assistant-state', 'success');
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('Keep your resume facts accurate.');
  await chat(page).getByRole('button', { name: 'Collapse assistant', exact: true }).click();
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'success');
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'idle');
  await button.click();
  await page.evaluate(() => {
    navigator.clipboard.writeText = async () => { throw new DOMException('Test clipboard denied', 'NotAllowedError'); };
    document.execCommand = () => false;
  });
  await chat(page).getByRole('button', { name: 'Copy assistant answer', exact: true }).last().click();
  await expect(chat(page)).toHaveAttribute('data-assistant-state', 'idle');
  await chat(page).getByRole('button', { name: 'Collapse assistant', exact: true }).click();
  fail = true;
  gate = new Promise<void>((resolve) => { release = resolve; });
  await button.click(); await input.fill('Help with my interview.'); await input.press('Enter');
  await chat(page).getByRole('button', { name: 'Collapse assistant', exact: true }).click();
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'thinking');
  release!(); await expect(pet(page)).toHaveAttribute('data-companion-state', 'error');
  await button.click(); await expect(chat(page).getByRole('alert')).toContainText('Companion lifecycle test failure');
  expect(Object.keys(requests[0]).sort()).toEqual(['context', 'history', 'message']);
  expect(requests[1].history).toEqual([{ role: 'user', content: 'Review my resume facts.' }, { role: 'assistant', content: 'Keep your resume facts accurate.' }]);
  expect(diagnostics.consoleErrors.filter((value) => !value.includes('502'))).toEqual([]);
});

test('real touch dragging clamps at the viewport edge without opening chat', async ({ page, context, diagnostics }) => {
  test.skip(!page.context().browser() || !test.info().project.name.startsWith('mobile'), 'Touch input is exercised on the mobile projects.');
  const button = await ready(page);
  const box = (await button.boundingBox())!;
  const session = await context.newCDPSession(page);
  const touch = (type: 'touchStart' | 'touchMove' | 'touchEnd', x: number, y: number) => session.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y, id: 1 }] });
  await touch('touchStart', box.x + box.width / 2, box.y + box.height / 2);
  for (let step = 1; step <= 10; step++) await touch('touchMove', Math.max(2, box.x + box.width / 2 - step * 35), Math.max(2, box.y + box.height / 2 - step * 55));
  await touch('touchEnd', 0, 0);
  await expect(chat(page)).toHaveCount(0);
  await expect(button).toBeVisible();
  await expect(page.locator('[data-assistant-mode="collapsed"]')).toHaveAttribute('data-placement-ready', 'true');
  await expect(pet(page)).toHaveAttribute('data-motion', 'idle');
  const end = (await button.boundingBox())!;
  expect(end.x).toBeGreaterThanOrEqual(15); expect(end.y).toBeGreaterThanOrEqual(15);
  await page.touchscreen.tap(end.x + end.width / 2, end.y + end.height / 2);
  await expect(chat(page)).toBeVisible();
  await session.detach();
  expect(diagnostics.consoleErrors).toEqual([]);
});

test('reduced motion and hidden-tab lifecycle freeze joint animation without losing state', async ({ page, diagnostics }) => {
  await ready(page);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(pet(page)).toHaveAttribute('data-active', '0');
  const initial = await pet(page).locator('[data-rig="head"]').getAttribute('transform');
  await page.waitForTimeout(300);
  expect(await pet(page).locator('[data-rig="head"]').getAttribute('transform')).toBe(initial);
  expect(await pet(page).evaluate((element) => element.getAnimations({ subtree: true }).length)).toBe(0);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await expect(pet(page)).toHaveAttribute('data-active', '1');
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }); document.dispatchEvent(new Event('visibilitychange')); });
  await expect(pet(page)).toHaveAttribute('data-active', '0');
  const frozen = await pet(page).getAttribute('data-frame');
  await page.waitForTimeout(250); expect(await pet(page).getAttribute('data-frame')).toBe(frozen);
  await page.evaluate(() => { delete (document as unknown as { hidden?: boolean }).hidden; document.dispatchEvent(new Event('visibilitychange')); });
  await expect(pet(page)).toHaveAttribute('data-active', '1');
  expect(diagnostics.consoleErrors).toEqual([]);
});

test('captures original artwork poses from real assistant lifecycle events', async ({ page, context, diagnostics }, info) => {
  test.skip(info.project.name !== 'desktop-1440x900', 'One enlarged artwork gallery is sufficient; responsive behavior is covered on every project.');
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  const button = await ready(page);
  const poses: Array<{ label: string; image: string }> = [];
  const capture = async (label: string) => {
    const canvas = button.locator('canvas');
    const frame = Number(await canvas.getAttribute('data-pixel-frame'));
    await expect.poll(async () => Number(await canvas.getAttribute('data-pixel-frame'))).toBeGreaterThan(frame);
    const image = await canvas.evaluate((element) => (element as HTMLCanvasElement).toDataURL());
    poses.push({ label, image });
  };
  await capture('Idle');
  const box = (await button.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
  await page.mouse.move(box.x - 60, box.y - 50, { steps: 15 });
  await expect(pet(page)).toHaveAttribute('data-motion', 'walking');
  await capture('Walking'); await page.mouse.up();
  await expect(page.locator('[data-assistant-mode="collapsed"]')).toHaveAttribute('data-placement-ready', 'true');
  let release: (() => void) | undefined;
  let gate = new Promise<void>((resolve) => { release = resolve; });
  let failed = false;
  await page.route('**/api/chat', async (route) => {
    await gate;
    await route.fulfill(failed ? { status: 502, json: { message: 'Gallery request failure' } } : { json: { reply: 'Use the career facts you have confirmed.', provider: 'Isolated visual test' } });
  });
  await button.click();
  const input = chat(page).getByRole('textbox'); await input.fill('Help me prepare for an interview.'); await input.press('Enter');
  await chat(page).getByRole('button', { name: 'Collapse assistant', exact: true }).click();
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'thinking');
  await expect.poll(async () => Number(await pet(page).getAttribute('data-frame'))).toBeGreaterThan(10);
  await capture('Thinking');
  release!(); await expect(pet(page)).toHaveAttribute('data-companion-state', 'answering');
  await expect.poll(async () => Number(await pet(page).getAttribute('data-frame'))).toBeGreaterThan(12);
  await capture('Answer ready');
  await button.click(); await chat(page).getByRole('button', { name: 'Copy assistant answer', exact: true }).last().click();
  await chat(page).getByRole('button', { name: 'Collapse assistant', exact: true }).click();
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'success');
  await expect.poll(async () => Number(await pet(page).getAttribute('data-frame'))).toBeGreaterThan(12);
  await capture('Copied');
  failed = true; gate = new Promise<void>((resolve) => { release = resolve; });
  await button.click(); await input.fill('Give me a next step.'); await input.press('Enter');
  await chat(page).getByRole('button', { name: 'Collapse assistant', exact: true }).click();
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'thinking'); release!();
  await expect(pet(page)).toHaveAttribute('data-companion-state', 'error');
  await expect.poll(async () => Number(await pet(page).getAttribute('data-frame'))).toBeGreaterThan(8);
  await capture('Error');
  const gallery = await context.newPage();
  await gallery.setViewportSize({ width: 660, height: 570 });
  await gallery.setContent(`<html><style>body{margin:0;padding:24px;background:#f6f7f9;color:#20242b;font:14px 'Segoe UI',sans-serif}h1{font-size:18px;margin:0 0 16px;font-weight:600}.grid{display:grid;grid-template-columns:repeat(3,1fr);gap:12px}.pose{display:grid;justify-items:center;background:white;border:1px solid #e5e8ed;border-radius:12px;padding:8px}.pose img{width:152px;height:198px;display:block;image-rendering:pixelated}.pose p{margin:0 0 4px}</style><body><h1>Smart Resume AI · pixel robot</h1><div class="grid">${poses.map(({ label, image }) => `<div class="pose"><img src="${image}" alt="${label}"/><p>${label}</p></div>`).join('')}</div></body></html>`);
  const folder = path.join(process.cwd(), 'scripts/visual-qa/mascot/pixel-companion');
  await mkdir(folder, { recursive: true });
  await gallery.screenshot({ path: path.join(folder, 'artwork-gallery.png'), caret: 'initial' });
  await gallery.close();
  const expected502 = 'Failed to load resource: the server responded with a status of 502 (Bad Gateway)';
  expect(diagnostics.consoleErrors.filter((message) => message !== expected502)).toEqual([]);
});
